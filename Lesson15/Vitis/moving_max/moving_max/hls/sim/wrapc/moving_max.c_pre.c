void moving_max(int in[64], int out[64])
{
    int window[8];


INITIALIZE_WINDOW:
    for (int window_index = 0; window_index < 8; ++window_index)
    {
        window[window_index] = (-2147483647 -1);
    }

PROCESS_SAMPLES:
    for (int sample_index = 0; sample_index < 64; ++sample_index)
    {

    SHIFT_WINDOW:
        for (int window_index = 8 - 1; window_index > 0; --window_index)
        {
            window[window_index] = window[window_index - 1];
        }


        window[0] = in[sample_index];

        int maximum = window[0];
    FIND_MAXIMUM:
        for (int window_index = 1; window_index < 8; ++window_index)
        {
            if (window[window_index] > maximum)
            {
                maximum = window[window_index];
            }
        }

        out[sample_index] = maximum;
    }
}
